"""Tiny claim-checking framework.

Every factual statement in a case write-up that carries a number is expressed as
a ``claim``: the expected value from the write-up, the value recomputed from raw
chain data, and the evidence (tx hashes / addresses) it was computed from.
Running a case module prints a PASS/FAIL table and writes a Markdown report.
"""
from __future__ import annotations

import traceback
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORTS = ROOT / "reports"


def D(x) -> Decimal:
    return Decimal(str(x))


def micro(amount: int | str, decimals: int = 6) -> Decimal:
    return Decimal(int(amount)) / (Decimal(10) ** decimals)


class Report:
    def __init__(self, case_id: str, title: str):
        self.case_id, self.title = case_id, title
        self.rows: list[dict] = []
        self.evidence: dict[str, str] = {}

    def claim(self, cid: str, text: str, expected, actual, tol=Decimal("0"), evidence=()):
        num=(int, float, Decimal)
        if isinstance(expected, num) and isinstance(actual, num) and not isinstance(expected, bool) and not isinstance(actual, bool):
            ok = abs(D(expected) - D(actual)) <= D(tol)
        else:
            ok = expected == actual
        self.rows.append({"id": cid, "text": text, "expected": expected, "actual": actual,
                          "ok": ok, "evidence": list(evidence)})
        mark = "PASS" if ok else "FAIL"
        print(f"[{mark}] {cid} {text}\n        expected={expected}  actual={actual}")
        return ok

    def note(self, cid: str, text: str, value, evidence=()):
        """Informational fact (no expected value) - still recorded with evidence."""
        self.rows.append({"id": cid, "text": text, "expected": "-", "actual": value, "ok": None,
                          "evidence": list(evidence)})
        print(f"[INFO] {cid} {text}: {value}")

    def ev(self, label: str, ref: str):
        """Register a full hash/address in the evidence index (labels made unique)."""
        base, i = label, 2
        while label in self.evidence and self.evidence[label] != ref:
            label = f"{base} ({i})"
            i += 1
        self.evidence[label] = ref

    def run(self, fn):
        try:
            fn(self)
        except Exception:
            traceback.print_exc()
            self.rows.append({"id": fn.__name__, "text": "check crashed", "expected": "-",
                              "actual": traceback.format_exc(limit=1), "ok": False, "evidence": []})

    def write(self):
        REPORTS.mkdir(exist_ok=True)
        n_ok = sum(1 for r in self.rows if r["ok"] is True)
        n_fail = sum(1 for r in self.rows if r["ok"] is False)
        from tools.manifest import snapshot_time
        snap = snapshot_time()
        snap_s = snap.strftime("%Y-%m-%d %H:%M UTC") if snap else "unknown"
        lines = [f"# Verification report — {self.title}", "",
                 f"Generated by `python -m checks.{self.case_id}` from raw chain data fetched {snap_s} "
                 f"(newest `fetched_at` in `data/cache/`, pinned by `data/cache/MANIFEST.sha256`).",
                 f"Result: **{n_ok} passed, {n_fail} failed**, "
                 f"{sum(1 for r in self.rows if r['ok'] is None)} informational.", "",
                 "| ID | Claim | Expected | Recomputed from chain | Result |", "|---|---|---|---|---|"]
        for r in self.rows:
            res = {True: "PASS", False: "**FAIL**", None: "info"}[r["ok"]]
            lines.append(f"| {r['id']} | {r['text']} | {r['expected']} | {r['actual']} | {res} |")
        lines += ["", "## Evidence used per claim", ""]
        for r in self.rows:
            if r["evidence"]:
                lines.append(f"- **{r['id']}**: " + ", ".join(f"`{e}`" for e in r["evidence"]))
        lines += ["", "## Evidence index (full hashes and addresses)", "", "| Label | Reference |", "|---|---|"]
        for k, v in self.evidence.items():
            lines.append(f"| {k} | `{v}` |")
        out = REPORTS / f"verification-{self.case_id}.md"
        out.write_text("\n".join(lines) + "\n")
        print(f"\n{n_ok} passed, {n_fail} failed -> {out.relative_to(ROOT)}")
        return n_fail == 0
